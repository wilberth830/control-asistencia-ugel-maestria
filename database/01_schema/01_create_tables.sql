            DBMS_OUTPUT.PUT_LINE('[OK] Primary key ' || UPPER(p_constraint_name) || ' ya existe');
        ELSIF primary_key_exists(p_table_name) THEN
            DBMS_OUTPUT.PUT_LINE('[OK] Tabla ' || UPPER(p_table_name) || ' ya tiene primary key');
        ELSE
            EXECUTE IMMEDIATE p_sql;
            DBMS_OUTPUT.PUT_LINE('[CREATE] Primary key ' || UPPER(p_constraint_name) || ' creada');
        END IF;
    END;

    PROCEDURE add_column_if_missing(
        p_table_name IN VARCHAR2,
