        p_table_name IN VARCHAR2,
        p_sql IN VARCHAR2
    ) IS
    BEGIN
        IF table_exists(p_table_name) THEN
            DBMS_OUTPUT.PUT_LINE('[OK] Tabla ' || UPPER(p_table_name) || ' ya existe');
        ELSE
            EXECUTE IMMEDIATE p_sql;
            DBMS_OUTPUT.PUT_LINE('[CREATE] Tabla ' || UPPER(p_table_name) || ' creada');
        END IF;
    END;

    PROCEDURE add_constraint_if_missing(
        p_constraint_name IN VARCHAR2,
